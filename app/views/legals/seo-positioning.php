        <h2 class="seo-tips">2. Optimización On-Page</h2>
        <ul>
            <li><strong>Título y Meta Descripciones:</strong> Asegúrate de que cada página tenga un título único y una meta descripción atractiva que incluya palabras clave.</li>
            <li><strong>Encabezados (H1, H2, H3, etc.):</strong> Usa encabezados para estructurar tu contenido y mejorar la legibilidad. Incluye palabras clave de forma natural.</li>
            <li><strong>Contenido de Calidad:</strong> Crea contenido valioso, relevante y bien investigado que responda a las preguntas de tu audiencia. Usa palabras clave de manera estratégica.</li>
            <li><strong>Optimización de Imágenes:</strong> Usa texto alternativo (alt text) descriptivo y relevante para las imágenes.</li>
            <li><strong>URLs Amigables:</strong> Asegúrate de que las URLs sean cortas y contengan palabras clave relevantes.</li>
        </ul>
        
    </section>

    <section id="tecnica">
        <h2 class="seo-tips">3. Optimización Técnica</h2>
        <ul>
            <li><strong>Velocidad del Sitio:</strong> Asegúrate de que tu sitio cargue rápidamente. Usa herramientas como Google PageSpeed Insights para analizar y mejorar la velocidad.</li>
            <li><strong>Mobile-Friendly:</strong> Tu sitio debe ser responsivo y funcionar bien en dispositivos móviles.</li>
            <li><strong>Sitemap y Robots.txt:</strong> Crea un <a href="https://ikusa.net/sitemap" target="_blank">sitemap XML</a>y un archivo robots.txt para ayudar a los motores de búsqueda a indexar tu sitio.</li>
            <li><strong>Enlaces Internos:</strong> Usa enlaces internos para ayudar a distribuir la autoridad de página y mejorar la navegación del sitio.</li>
        </ul>
     
    </section>

    <section id="offpage">
        <h2 class="seo-tips">4. Optimización Off-Page</h2>
        <ul>
